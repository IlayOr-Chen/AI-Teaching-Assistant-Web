"""
Purpose:
    Implements `VideoSummarizer` for Feature 4 (AI Lecture Video Summary — YouTube URL Only +
    Automatic 2-Step Fast Strategy + YouTube oEmbed Video Title) persisted in Firebase
    Realtime Database under `/video_summaries`.
    - Validates and canonicalizes public YouTube URLs (stripping playlist parameters `&list=...`,
      `&index=...`, etc. down to `https://www.youtube.com/watch?v=<video_id>`).
    - Fetches the real UTF-8 YouTube video title via YouTube's public oEmbed endpoint
      (`https://www.youtube.com/oembed?url=<clean_url>&format=json`, ~5s timeout), falling
      back gracefully to a short title generated by Gemini or the video ID.
    - Step 1 (Fastest — handles 45-90 min lectures in seconds): Uses `youtube-transcript-api`
      to fetch the video's transcript (preferring Hebrew `["he", "iw"]` and English `["en"]`,
      including auto-generated captions) and passes the transcript text directly to `GeminiClient`.
    - Step 2 (Automatic Fallback if captions are disabled/unavailable): Passes the canonical
      YouTube URL directly to `GeminiClient` using `types.Part` with `VideoMetadata(fps=0.1)`
      (falling back automatically to plain `Part.from_uri` if `video_metadata` returns HTTP 400).
    - Generates a rich, structured English academic summary (`video_title`, `source_url`,
      `executive_summary`, `detailed_overview`, `key_concepts`, `key_topics`,
      `core_takeaways`, `study_questions`, `action_items`, and `delivery_insights`).
Inputs:
    `FirebaseRepository` persistence instance and `GeminiClient` AI wrapper.
Outputs:
    `VideoSummarizer` class managing YouTube URL canonicalization, oEmbed title fetching,
    2-step transcript/video analysis, rich Gemini academic summarization, and persistence.
"""

from __future__ import annotations

import logging
import re
import secrets
import time
from typing import Any
from urllib.parse import parse_qs, quote, urlparse

import httpx

from src.repository.firebase_repository import FirebaseRepository
from src.services.gemini_client import GeminiClient

logger = logging.getLogger(__name__)

PREFERRED_TRANSCRIPT_LANGUAGES = ("he", "iw", "en", "en-US", "en-GB")


class VideoSummarizer:
    """
    Purpose:
        Domain service that validates and canonicalizes public YouTube lecture video URLs,
        fetches the real YouTube video title via public oEmbed, executes the automatic
        2-step summarization strategy (Step 1: `youtube-transcript-api` fast transcript
        extraction -> Gemini text analysis; Step 2: direct YouTube URI with
        `VideoMetadata(fps=0.1)` via `GeminiClient`), and stores rich structured academic
        summaries in Firebase RTDB (`/video_summaries`). Contains zero fake or hardcoded
        fallback summaries.
    Inputs:
        repository (FirebaseRepository): Firebase RTDB persistence layer.
        gemini_client (GeminiClient): Configured Gemini AI client.
    Outputs:
        `VideoSummarizer` service instance.
    """

    def __init__(
        self, repository: FirebaseRepository, gemini_client: GeminiClient
    ) -> None:
        """
        Purpose:
            Initialize `VideoSummarizer` with a Firebase repository and `GeminiClient`.
        Inputs:
            repository (FirebaseRepository): Target Firebase RTDB repository.
            gemini_client (GeminiClient): Gemini client instance.
        Outputs:
            None.
        """
        self.repository = repository
        self.gemini_client = gemini_client

    @staticmethod
    def validate_youtube_url(youtube_url: str) -> str:
        """
        Purpose:
            Validate a public YouTube URL (`youtube.com/watch?v=...&list=...&index=1`,
            `youtu.be/...`, `youtube.com/shorts/...`, `youtube.com/live/...`,
            `youtube.com/embed/...`), strip all playlist/timestamp query parameters, and
            normalize it strictly to `https://www.youtube.com/watch?v=<video_id>`.
        Inputs:
            youtube_url (str): Raw YouTube URL submitted by the Lecturer.
        Outputs:
            str: Canonical `https://www.youtube.com/watch?v=<video_id>` URL.
            Raises `ValueError` if the URL is empty or not a valid YouTube video link.
        """
        clean = (youtube_url or "").strip()
        if not clean:
            raise ValueError("A public YouTube URL is required.")

        parsed = urlparse(clean)
        host = parsed.netloc.lower()
        if host.startswith("www."):
            host = host[4:]
        if host.startswith("m."):
            host = host[2:]

        video_id: str | None = None
        if host == "youtu.be":
            parts = [p for p in parsed.path.strip("/").split("/") if p]
            if parts:
                video_id = parts[0]
        elif host in {"youtube.com", "youtube-nocookie.com"}:
            path_parts = [p for p in parsed.path.strip("/").split("/") if p]
            if not path_parts or path_parts[0] == "watch":
                qs = parse_qs(parsed.query)
                v_list = qs.get("v", [])
                if v_list:
                    video_id = v_list[0]
            elif len(path_parts) >= 2 and path_parts[0] in {
                "shorts",
                "embed",
                "live",
                "v",
            }:
                video_id = path_parts[1]

        if not video_id or not re.match(r"^[A-Za-z0-9_-]{6,20}$", video_id):
            raise ValueError(
                "Invalid YouTube URL. Please provide a valid public YouTube link "
                "(e.g., https://www.youtube.com/watch?v=... or https://youtu.be/...)."
            )

        return f"https://www.youtube.com/watch?v={video_id}"

    @staticmethod
    def _fetch_youtube_title(canonical_url: str) -> str | None:
        """
        Purpose:
            Fetch the real UTF-8 video title for `canonical_url` from YouTube's free
            public oEmbed endpoint (`https://www.youtube.com/oembed?url=...&format=json`)
            with a short 5-second timeout so Hebrew and English lecture titles display
            cleanly in summary card headers.
        Inputs:
            canonical_url (str): Canonical YouTube URL (`https://www.youtube.com/watch?v=...`).
        Outputs:
            str | None: Video title string if retrieved successfully, else None.
        """
        oembed_url = (
            f"https://www.youtube.com/oembed?url={quote(canonical_url, safe='')}&format=json"
        )
        try:
            with httpx.Client(timeout=5.0, follow_redirects=True) as client:
                resp = client.get(oembed_url)
            if resp.status_code != 200:
                return None
            data = resp.json()
            if isinstance(data, dict):
                title = str(data.get("title") or "").strip()
                if title:
                    return title
        except Exception as exc:
            logger.info(
                "YouTube oEmbed title lookup skipped/failed for '%s': %s",
                canonical_url,
                exc,
            )
        return None

    @staticmethod
    def _fetch_youtube_transcript(video_id: str) -> str | None:
        """
        Purpose:
            Attempt to fetch the spoken transcript for a YouTube `video_id` using
            `youtube-transcript-api` (supporting both Hebrew `["he", "iw"]` and English
            `["en"]`, manual or auto-generated captions, and both v1.x `.fetch()` and
            legacy `.get_transcript()` APIs).
        Inputs:
            video_id (str): Extracted YouTube video ID.
        Outputs:
            str | None: Joined transcript text if available and non-empty, else None.
        """
        try:
            from youtube_transcript_api import YouTubeTranscriptApi

            items: Any = None
            if hasattr(YouTubeTranscriptApi, "fetch"):
                api = YouTubeTranscriptApi()
                try:
                    items = api.fetch(
                        video_id, languages=list(PREFERRED_TRANSCRIPT_LANGUAGES)
                    )
                except Exception:
                    if hasattr(api, "list"):
                        t_list = api.list(video_id)
                        first_t = next(iter(t_list), None)
                        if first_t is not None:
                            items = first_t.fetch()
            elif hasattr(YouTubeTranscriptApi, "get_transcript"):
                items = YouTubeTranscriptApi.get_transcript(
                    video_id, languages=list(PREFERRED_TRANSCRIPT_LANGUAGES)
                )

            if items is None:
                return None

            snippets: list[str] = []
            for entry in items:
                text_val = (
                    entry.get("text", "")
                    if isinstance(entry, dict)
                    else getattr(entry, "text", "")
                )
                clean_seg = str(text_val or "").strip()
                if clean_seg:
                    snippets.append(clean_seg)

            joined = " ".join(snippets).strip()
            return joined if joined else None
        except Exception as exc:
            logger.info(
                "YouTube transcript not available for video_id='%s' (%s); falling back to direct video URI analysis.",
                video_id,
                exc,
            )
            return None

    @staticmethod
    def _build_prompt(
        canonical_url: str,
        lesson_tag: str,
        lecturer_notes: str,
        transcript_text: str | None = None,
        video_title: str | None = None,
    ) -> str:
        """
        Purpose:
            Construct the structured Gemini instruction prompt requesting a thorough,
            content-faithful English academic lecture recap from either the extracted
            YouTube lecture transcript or the YouTube video stream.
        Inputs:
            canonical_url (str): Canonical YouTube URL (`https://www.youtube.com/watch?v=...`).
            lesson_tag (str): Lesson tag (e.g., `"Lesson 2"`).
            lecturer_notes (str): Optional context notes provided by the lecturer.
            transcript_text (str | None): Optional extracted YouTube transcript text.
            video_title (str | None): Optional real YouTube title from oEmbed.
        Outputs:
            str: Prompt string for `GeminiClient`.
        """
        notes_clause = (
            f"\nOptional Lecturer Context Notes: {lecturer_notes.strip()}"
            if lecturer_notes and lecturer_notes.strip()
            else ""
        )
        title_clause = (
            f"\nVideo Title: '{video_title.strip()}'"
            if video_title and video_title.strip()
            else ""
        )
        transcript_clause = (
            f"\n\nExtracted Lecture Transcript (analyze thoroughly):\n{transcript_text[:60_000]}"
            if transcript_text and transcript_text.strip()
            else ""
        )
        return (
            "You are an expert university AI Teaching Assistant. Carefully analyze the ACTUAL "
            "content taught in this YouTube lecture recording. Even if the lecturer speaks in Hebrew "
            "or another language, write your entire output in clear, accurate English based strictly "
            "on the real subject matter, definitions, examples, and proofs taught in the lecture. "
            "Never invent generic filler topics that are not in the lecture.\n"
            "Return ONLY a valid JSON object with these exact keys:\n"
            '- "suggested_title": string (short, descriptive lecture title if none was provided)\n'
            '- "executive_summary": string (2-4 crisp sentences serving as a quick TL;DR headline recap of what was taught)\n'
            '- "detailed_overview": string (1-2 cohesive, detailed academic paragraphs separated by "\\n\\n" explaining what actually happened in the lecture — the main storyline, how concepts connected step-by-step, and specific examples, proofs, or arguments discussed)\n'
            '- "key_concepts": list of 3-6 objects, each with exact keys {"term": "Core term, theorem, formula, or algorithm name", "explanation": "Clear 1-2 sentence explanation of how it was defined or applied in the lecture"}\n'
            '- "key_topics": list of 3-6 specific topics, algorithms, or themes covered in the lecture\n'
            '- "core_takeaways": list of 3-5 concrete student learning takeaways from the lecture\n'
            '- "study_questions": list of 2-3 concise self-check or exam-style review questions based directly on the lecture content\n'
            '- "action_items": list of 2-4 actionable practice steps or review tasks for students based on the lecture\n'
            '- "delivery_insights": object with keys "pacing", "clarity", "audio_quality", '
            'and "overall_rating" ("Excellent" | "Good" | "Needs Attention") evaluating the lecturer\'s delivery.\n'
            f"YouTube Lecture URL: '{canonical_url}', Lesson Tag: '{lesson_tag}'.{title_clause}{notes_clause}{transcript_clause}"
        )

    @staticmethod
    def _normalize_key_concepts(raw_concepts: Any) -> list[dict[str, str]]:
        """
        Purpose:
            Normalize `key_concepts` from Gemini JSON (or older records) into a clean list
            of `{"term": str, "explanation": str}` dictionaries.
        Inputs:
            raw_concepts (Any): Raw `key_concepts` field from Gemini output or Firebase record.
        Outputs:
            list[dict[str, str]]: Sanitized list of concept dictionaries.
        """
        if not isinstance(raw_concepts, list):
            return []
        normalized: list[dict[str, str]] = []
        for item in raw_concepts:
            if isinstance(item, dict):
                term = str(
                    item.get("term")
                    or item.get("concept")
                    or item.get("name")
                    or ""
                ).strip()
                explanation = str(
                    item.get("explanation")
                    or item.get("definition")
                    or item.get("description")
                    or ""
                ).strip()
                if term or explanation:
                    normalized.append(
                        {
                            "term": term or "Concept",
                            "explanation": explanation,
                        }
                    )
            elif isinstance(item, str) and item.strip():
                parts = item.split(":", 1)
                if len(parts) == 2:
                    normalized.append(
                        {"term": parts[0].strip(), "explanation": parts[1].strip()}
                    )
                else:
                    normalized.append({"term": "Key Concept", "explanation": item.strip()})
        return normalized

    def summarize_video(
        self,
        youtube_url: str,
        lesson_tag: str = "Lesson 1",
        lecturer_notes: str = "",
        gemini_api_key: str | None = None,
        gemini_model_id: str | None = None,
    ) -> dict[str, Any]:
        """
        Purpose:
            Validate and canonicalize a public YouTube lecture URL, fetch the real UTF-8
            video title via YouTube oEmbed, execute the automatic 2-step fast summarization
            strategy (Step 1: `youtube-transcript-api` -> Gemini text analysis; Step 2:
            direct YouTube URI with `VideoMetadata(fps=0.1)`), and persist the rich structured
            academic summary (`video_title`, `source_url`, `detailed_overview`, `key_concepts`,
            `study_questions`, etc.) in Firebase RTDB under `/video_summaries/{id}`.
        Inputs:
            youtube_url (str): Public YouTube URL to analyze.
            lesson_tag (str): Associated lesson tag (e.g., `"Lesson 1"`).
            lecturer_notes (str): Optional context notes from the lecturer.
            gemini_api_key (str | None): Optional BYOK API key override from request header.
            gemini_model_id (str | None): Optional BYOK model ID override from request header.
        Outputs:
            dict[str, Any]: Persisted structured lecture video summary record.
            Raises `ValueError` for invalid YouTube URLs or `RuntimeError` if Gemini fails.
        """
        clean_tag = (lesson_tag or "Lesson 1").strip() or "Lesson 1"
        canonical_yt = self.validate_youtube_url(youtube_url)
        video_id = canonical_yt.split("v=")[-1]

        oembed_title = self._fetch_youtube_title(canonical_yt)
        transcript_text = self._fetch_youtube_transcript(video_id)

        if transcript_text:
            analysis_source = "youtube_transcript"
            prompt = self._build_prompt(
                canonical_url=canonical_yt,
                lesson_tag=clean_tag,
                lecturer_notes=lecturer_notes,
                transcript_text=transcript_text,
                video_title=oembed_title,
            )
            generated = self.gemini_client.generate_structured_json(
                prompt=prompt,
                api_key_override=gemini_api_key,
                model_id_override=gemini_model_id,
            )
        else:
            analysis_source = "youtube_video_fps_0.1"
            prompt = self._build_prompt(
                canonical_url=canonical_yt,
                lesson_tag=clean_tag,
                lecturer_notes=lecturer_notes,
                transcript_text=None,
                video_title=oembed_title,
            )
            generated = self.gemini_client.generate_structured_json(
                prompt=prompt,
                file_uri=canonical_yt,
                mime_type="video/mp4",
                api_key_override=gemini_api_key,
                model_id_override=gemini_model_id,
            )

        now_ts = int(time.time())
        summary_id = f"vid_{now_ts}_{secrets.token_hex(4)}"
        delivery = (
            generated.get("delivery_insights")
            if isinstance(generated.get("delivery_insights"), dict)
            else {}
        )
        resolved_title = (
            oembed_title
            or str(generated.get("suggested_title") or generated.get("video_title") or "").strip()
            or f"YouTube Lecture ({video_id})"
        )
        exec_summary = str(
            generated.get("executive_summary")
            or generated.get("summary")
            or ""
        ).strip()
        detailed_overview = str(
            generated.get("detailed_overview")
            or generated.get("walkthrough")
            or ""
        ).strip()
        key_concepts = self._normalize_key_concepts(generated.get("key_concepts"))
        takeaways = [
            str(t).strip()
            for t in (
                generated.get("core_takeaways")
                or generated.get("takeaways")
                or []
            )
            if str(t).strip()
        ]
        study_questions = [
            str(q).strip()
            for q in (
                generated.get("study_questions")
                or generated.get("review_questions")
                or []
            )
            if str(q).strip()
        ]
        key_topics = [
            str(t).strip()
            for t in (generated.get("key_topics") or [])
            if str(t).strip()
        ]
        action_items = [
            str(a).strip()
            for a in (generated.get("action_items") or [])
            if str(a).strip()
        ]

        record: dict[str, Any] = {
            "summary_id": summary_id,
            "video_title": resolved_title,
            "source_url": canonical_yt,
            "filename": resolved_title,
            "source_type": "youtube",
            "analysis_method": analysis_source,
            "youtube_url": canonical_yt,
            "file_size_kb": 0.0,
            "lesson_tag": clean_tag,
            "lecturer_notes": (lecturer_notes or "").strip(),
            "executive_summary": exec_summary,
            "detailed_overview": detailed_overview,
            "key_concepts": key_concepts,
            "key_topics": key_topics,
            "core_takeaways": takeaways,
            "study_questions": study_questions,
            "action_items": action_items,
            "delivery_insights": {
                "pacing": str(delivery.get("pacing", "Balanced lecture pacing.")),
                "clarity": str(
                    delivery.get("clarity", "Clear explanations and examples.")
                ),
                "audio_quality": str(
                    delivery.get("audio_quality", "Clear audio track.")
                ),
                "overall_rating": str(delivery.get("overall_rating", "Excellent")),
            },
            "model_used": str(generated.get("model_used", "gemini-3.5-flash-lite")),
            "provider": str(generated.get("provider", "gemini_live")),
            "created_at": now_ts,
        }
        self.repository.set(f"/video_summaries/{summary_id}", record)
        return record

    def list_summaries(self) -> list[dict[str, Any]]:
        """
        Purpose:
            Retrieve all stored lecture video summaries from `/video_summaries`,
            ordered newest-first, ensuring backwards-compatible default fields
            (`video_title`, `source_url`, `detailed_overview`, `key_concepts`,
            `study_questions`) for older saved records.
        Inputs:
            None.
        Outputs:
            list[dict[str, Any]]: Ordered list of lecture video summary records.
        """
        raw_all = self.repository.get("/video_summaries")
        if not isinstance(raw_all, dict):
            return []
        items: list[dict[str, Any]] = []
        for sid, v in raw_all.items():
            if not isinstance(v, dict):
                continue
            item = dict(v)
            item["summary_id"] = str(item.get("summary_id") or sid)
            source_url = str(
                item.get("source_url")
                or item.get("youtube_url")
                or (
                    item.get("filename")
                    if str(item.get("filename") or "").startswith("http")
                    else ""
                )
            ).strip()
            item["source_url"] = source_url or None
            if not item.get("youtube_url") and source_url:
                item["youtube_url"] = source_url
            video_title = str(item.get("video_title") or "").strip()
            if not video_title:
                raw_fn = str(item.get("filename") or "").strip()
                video_title = (
                    raw_fn
                    if raw_fn and not raw_fn.startswith("http")
                    else f"{item.get('lesson_tag') or 'Lecture'} Video Summary"
                )
            item["video_title"] = video_title
            item.setdefault("detailed_overview", "")
            item["key_concepts"] = self._normalize_key_concepts(
                item.get("key_concepts")
            )
            item.setdefault("study_questions", [])
            item.setdefault("key_topics", [])
            item.setdefault("core_takeaways", [])
            item.setdefault("action_items", [])
            items.append(item)
        items.sort(key=lambda s: int(s.get("created_at", 0)), reverse=True)
        return items

    def delete_summary(self, summary_id: str) -> dict[str, Any]:
        """
        Purpose:
            Delete a persisted lecture video summary record from `/video_summaries/{summary_id}`
            in Firebase RTDB.
        Inputs:
            summary_id (str): Unique identifier of the video summary to remove.
        Outputs:
            dict[str, Any]: Deletion confirmation dictionary (`summary_id`, `status="deleted"`).
            Raises `ValueError` if `summary_id` is empty or does not exist.
        """
        clean_id = re.sub(r"[.$#\[\]/]", "_", (summary_id or "").strip())
        if not clean_id:
            raise ValueError("summary_id is required.")

        existing = self.repository.get(f"/video_summaries/{clean_id}")
        if not isinstance(existing, dict):
            raise ValueError(f"Video summary '{clean_id}' was not found.")

        self.repository.delete(f"/video_summaries/{clean_id}")
        return {"summary_id": clean_id, "status": "deleted"}
